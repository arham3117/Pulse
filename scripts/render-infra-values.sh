#!/usr/bin/env bash
# Render pulse-gitops/envs/<ENV>/infra-values.yaml from Terraform outputs.
#
# The file contains only non-secret identifiers (URLs, names, ARNs), so it is
# safe to commit. Schema is fixed by docs/CONTRACT.md.
#
# Usage: scripts/render-infra-values.sh dev|prod
# Env:   PULSE_GITOPS_DIR  override the gitops checkout (default: <repo>/pulse-gitops)
set -euo pipefail

usage() {
  cat >&2 <<EOF
Usage: $(basename "$0") ENV

Reads 'terraform output -json' from infra/envs/ENV and writes
\${PULSE_GITOPS_DIR:-<repo>/pulse-gitops}/envs/ENV/infra-values.yaml.

  ENV   dev | prod
EOF
  exit 2
}

die() {
  echo "error: $*" >&2
  exit 1
}

[[ $# -eq 1 ]] || usage
ENV="$1"
case "${ENV}" in
  dev | prod) ;;
  -h | --help) usage ;;
  *) echo "error: unknown environment '${ENV}'" >&2; usage ;;
esac

for bin in terraform jq; do
  command -v "${bin}" >/dev/null 2>&1 || die "'${bin}' is required but not installed"
done

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TF_DIR="${REPO_ROOT}/infra/envs/${ENV}"
GITOPS_DIR="${PULSE_GITOPS_DIR:-${REPO_ROOT}/pulse-gitops}"
OUT_DIR="${GITOPS_DIR}/envs/${ENV}"
OUT_FILE="${OUT_DIR}/infra-values.yaml"

[[ -d "${TF_DIR}" ]] || die "terraform root not found: ${TF_DIR}"
[[ -d "${GITOPS_DIR}" ]] || die "gitops checkout not found: ${GITOPS_DIR}"

outputs_json="$(terraform -chdir="${TF_DIR}" output -json)" \
  || die "terraform output failed (is infra/envs/${ENV} initialised and applied?)"

[[ -n "${outputs_json}" && "${outputs_json}" != "{}" ]] \
  || die "no terraform outputs for ${ENV}; apply the environment first"

# Every output the contract requires. acm_certificate_arn may be an empty string.
required=(
  region cluster_name ecr_repository_url sqs_queue_url sqs_queue_name sqs_dlq_url
  db_host db_port db_name rds_master_secret_arn app_secret_name grafana_secret_name
  alertmanager_secret_name acm_certificate_arn vpc_id
)
missing=()
for key in "${required[@]}"; do
  if ! jq -e --arg k "${key}" 'has($k)' <<<"${outputs_json}" >/dev/null; then
    missing+=("${key}")
  elif [[ "${key}" != "acm_certificate_arn" ]] \
    && ! jq -e --arg k "${key}" '.[$k].value | . != null and . != ""' <<<"${outputs_json}" >/dev/null; then
    missing+=("${key} (empty)")
  fi
done
if ((${#missing[@]} > 0)); then
  die "missing terraform outputs: ${missing[*]}"
fi

cluster_name="$(jq -r '.cluster_name.value' <<<"${outputs_json}")"
[[ "${cluster_name}" == "pulse-${ENV}" ]] \
  || die "cluster_name '${cluster_name}' does not match environment '${ENV}'"

mkdir -p "${OUT_DIR}"
tmp_file="$(mktemp "${OUT_DIR}/.infra-values.yaml.XXXXXX")"
trap 'rm -f "${tmp_file}"' EXIT

# y: emit a YAML scalar. Plain style when safe (matches CONTRACT.md layout),
# otherwise a JSON string (valid YAML double-quoted scalar), e.g. "" for no ACM cert.
jq -r --arg env "${ENV}" '
  def y:
    if type == "number" then tostring
    elif type == "string"
      and test("^[A-Za-z0-9][A-Za-z0-9._/:@+-]*$")
      and (test("^(true|false|yes|no|on|off|null|~|[-+]?[0-9][0-9._eE+-]*)$"; "i") | not)
    then .
    else tojson
    end;
  def v($k): .[$k].value;
  [
    "# GENERATED by pulse/scripts/render-infra-values.sh from terraform outputs. Do not edit.",
    "global:",
    "  env: \($env | y)",
    "  awsRegion: \(v("region") | y)",
    "  clusterName: \(v("cluster_name") | y)",
    "image:",
    "  repository: \(v("ecr_repository_url") | y)",
    "infra:",
    "  sqsQueueUrl: \(v("sqs_queue_url") | y)",
    "  sqsQueueName: \(v("sqs_queue_name") | y)",
    "  sqsDlqUrl: \(v("sqs_dlq_url") | y)",
    "  dbHost: \(v("db_host") | y)",
    "  dbPort: \(v("db_port") | tonumber | y)",
    "  dbName: \(v("db_name") | y)",
    "  rdsMasterSecretArn: \(v("rds_master_secret_arn") | y)",
    "  appSecretName: \(v("app_secret_name") | y)",
    "  grafanaSecretName: \(v("grafana_secret_name") | y)",
    "  alertmanagerSecretName: \(v("alertmanager_secret_name") | y)",
    "  acmCertificateArn: \(v("acm_certificate_arn") // "" | y)",
    "  vpcId: \(v("vpc_id") | y)"
  ] | .[]
' <<<"${outputs_json}" >"${tmp_file}"

chmod 0644 "${tmp_file}"
mv "${tmp_file}" "${OUT_FILE}"
trap - EXIT

echo "wrote ${OUT_FILE}"

# The AWS Load Balancer Controller can't discover its VPC through IMDS (hop limit 1), so
# its Argo CD values need vpcId too. Rewrite just that line in the platform overrides.
ALB_FILE="${OUT_DIR}/platform/aws-load-balancer-controller.yaml"
if [[ -f "${ALB_FILE}" ]]; then
  vpc_id="$(jq -r '.vpc_id.value' <<<"${outputs_json}")"
  [[ "${vpc_id}" =~ ^vpc-[0-9a-f]+$ ]] || die "unexpected vpc_id '${vpc_id}'"
  sed -i.bak -E "s/^vpcId:.*/vpcId: ${vpc_id}   # set by render-infra-values.sh/" "${ALB_FILE}"
  rm -f "${ALB_FILE}.bak"
  echo "updated vpcId in ${ALB_FILE}"
fi
